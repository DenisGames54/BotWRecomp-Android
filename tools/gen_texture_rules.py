"""Convert the [TextureRedefine] rules of Cemu's BotW "Graphics" pack (CC0) into a C++ table for the
built-in resolution scaling (runtime/cemu_shims/graphic_pack_shim.cpp). Shadow-map rules ($shadowRes)
are skipped; resolution expressions become scale * N (+ 0.49 where the pack adds it).

usage: uv run python -I tools/gen_texture_rules.py <Graphics/rules.txt> runtime/cemu_shims/botw_texture_rules.inc
"""
import re
import sys

KEYS = {"width", "height", "depth", "formats", "formatsexcluded", "tilemodes", "tilemodesexcluded",
        "overwriteformat", "overwritewidth", "overwriteheight"}


def nums(v: str) -> list[int]:
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", v)]


def scaled(expr: str) -> tuple[int, float] | None:
    if "$shadowRes" in expr:
        return None
    m = re.search(r"\*\s*(\d+)\)?\s*(\+\s*([\d.]+))?\s*$", expr)
    if not m or "$width" not in expr and "$height" not in expr:
        raise ValueError(f"unexpected expression: {expr}")
    return int(m.group(1)), float(m.group(3) or 0)


def main() -> None:
    src, out = sys.argv[1], sys.argv[2]
    rules, cur = [], None
    for line in open(src, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if line.startswith("["):
            cur = {} if line.startswith("[TextureRedefine]") else None
            if cur is not None:
                rules.append(cur)
            continue
        if cur is None or "=" not in line:
            continue
        k, v = (s.strip() for s in line.split("=", 1))
        if k.lower() in KEYS:
            cur[k.lower()] = v
    rows = []
    for r in rules:
        w, h = scaled(r["overwritewidth"]), scaled(r["overwriteheight"])
        if w is None or h is None:
            continue  # shadow maps
        lst = lambda k: "{" + ", ".join(f"0x{x:03x}" for x in nums(r.get(k, ""))) + "}"
        rows.append(f"    {{{int(r['width'])}, {int(r['height'])}, {int(r.get('depth', '-1'))}, {lst('formats')}, "
                    f"{lst('formatsexcluded')}, {lst('tilemodes')}, {lst('tilemodesexcluded')}, "
                    f"{int(r.get('overwriteformat', '-1'), 0)}, {w[0]}, {w[1]}, {h[0]}, {h[1]}}},")
    text = ("// Generated by tools/gen_texture_rules.py from the [TextureRedefine] rules of Cemu's BotW Graphics\n"
            "// pack (cemu_graphic_packs, CC0; by Kiri, Skalfate, rajkosto, NAVras). Do not edit.\n"
            "// width, height, depth, formats, formats excluded, tile modes, tile modes excluded,\n"
            "// overwrite format, overwrite width = scale * N (+ add), overwrite height = scale * N (+ add)\n"
            + "\n".join(rows) + "\n")
    with open(out, "w") as f:
        f.write(text)
    print(f"{len(rows)} rules ({len(rules) - len(rows)} shadow rules skipped)")


if __name__ == "__main__":
    main()
